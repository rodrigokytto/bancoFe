export interface BusinessMetrics {
  monthlyVolume: number; // Volume financeiro transacionado ou gerido em R$
  monthlyTransactions: number; // Qtd transações no mês
  uptimeSla: number; // ex: 99.98%
  avgLatencyMs: number; // ex: 16ms
  monthlySavings: number; // Economia estimada / ROI mensal gerado em R$
  activeUsersCount: number; // Total de operadores/usuários ativos
  hoursSavedMonthly: number; // Horas de trabalho economizadas pela automação
  complianceScore: number; // 99.8% conformidade
}

export interface ModuleTelemetry {
  monthlyRequests?: number; // ex: 42800 chamadas/mês
  uptimePercent?: number; // ex: 99.99%
  avgLatencyMs?: number; // ex: 14ms
  status?: "healthy" | "warning" | "idle";
  monthlyVolume?: number; // Volume financeiro operado pelo módulo em R$
  costReduction?: number; // Economia mensal proporcionada em R$
  usersCount?: number; // Operadores ativos
  lastSync?: string;
}

